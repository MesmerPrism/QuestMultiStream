import test from 'node:test';
import assert from 'node:assert/strict';

test('actual app callbacks recover status and preserve terminal errors/stop generation', async()=>{
  const nodes=new Map(),intervals=[],requests=[],listeners=new Map(),canvasResets=[],draws=[];let clock=1000,liveDecoder,liveSocket,sourceWidth=1344,sourceHeight=704;
  const context={drawImage(...args){draws.push(args);},clearRect(){},putImageData(){},getImageData(x,y,w,h){return {data:new Uint8ClampedArray(w*h*4)};}};
  function dimensions(node,id,width,height){for(const [key,initial] of [['width',width],['height',height]]){let value=initial;Object.defineProperty(node,key,{get:()=>value,set(next){value=next;canvasResets.push({id,key,value:next});}});}return node;}
  const element=id=>{if(!nodes.has(id))nodes.set(id,{value:id==='source'?'q':id==='view'?'full':'',textContent:'',style:{},options:[{}],files:[],hidden:false,append(o){this.options.push(o);},getContext(){return context;},pause(){},removeAttribute(){}});return nodes.get(id);};
  dimensions(element('screen'),'screen',1344,704);
  globalThis.document={hidden:false,getElementById:element,createElement:tag=>tag==='canvas'?dimensions({getContext:()=>context},'scratch',300,150):{},addEventListener(name,callback){listeners.set(name,callback);}};
  globalThis.location={hash:'#token=fixture',pathname:'/',host:'127.0.0.1:43118'};
  globalThis.sessionStorage={getItem(){return null;},setItem(){}};globalThis.history={replaceState(){}};
  globalThis.performance={now:()=>clock};globalThis.setInterval=f=>intervals.push(f);
  globalThis.window={VideoDecoder:true};
  globalThis.fetch=async(url,options)=>{requests.push({url,options});return {ok:true,json:async()=>url.startsWith('/api/sources')?[]:{available:false}};};
  globalThis.WebSocket=class {static OPEN=1;constructor(){this.readyState=1;liveSocket=this;}close(){this.readyState=3;this.onclose?.();}};
  globalThis.VideoDecoder=class {constructor(options){this.options=options;this.decodeQueueSize=0;this.state='configured';this.submitted=[];this.hasKey=false;liveDecoder=this;}configure(){}close(){this.state='closed';}decode(chunk){assert.ok(this.hasKey||chunk.type==='key','a new decoder cannot consume a dependent delta');this.hasKey=true;this.submitted.push(chunk);this.options.output({displayWidth:sourceWidth,displayHeight:sourceHeight,close(){}});}};
  globalThis.EncodedVideoChunk=class {constructor(options){Object.assign(this,options);}};
  await import('./app.mjs?actual-callback-control');
  await element('connect').onclick();liveSocket.onopen();
  const body=(config,key,pts,data)=>{const b=new Uint8Array(12+data.length),v=new DataView(b.buffer);v.setBigUint64(0,(config?1n<<63n:0n)|(key?1n<<62n:0n)|BigInt(pts));v.setUint32(8,data.length);b.set(data,12);return b.buffer;};
  await liveSocket.onmessage({data:body(true,false,0,[0,0,0,1,0x67,0x64,0,0x1f])});
  const frame=async(key,pts)=>liveSocket.onmessage({data:body(false,key,pts,[0,0,1,0x65])});
  await frame(true,1);assert.match(element('status').textContent,/H\.264 · Live host/);
  const originalDecoder=liveDecoder,drawsBeforeBurst=draws.length;
  liveDecoder.decodeQueueSize=9;await frame(false,2);
  liveDecoder.decodeQueueSize=15;await frame(false,3);
  assert.equal(liveDecoder,originalDecoder,'soft delta pressure preserves decoder references');
  assert.deepEqual(originalDecoder.submitted.map(c=>c.timestamp),[1,2,3]);
  assert.equal(draws.length,drawsBeforeBurst+2,'soft burst continues drawing every dependent frame');
  assert.equal(element('empty').hidden,true);assert.equal(canvasResets.length,0,'unchanged full-frame canvas dimensions are reused');
  clock+=1000;liveDecoder.decodeQueueSize=9;await frame(true,4);
  assert.notEqual(liveDecoder,originalDecoder,'pressure resets at the keyframe boundary');assert.equal(originalDecoder.state,'closed');
  assert.equal(liveDecoder.submitted[0].type,'key');assert.equal(liveDecoder.submitted[0].timestamp,4);
  assert.equal(liveDecoder.submitted[0].data.length,12,'configuration is prepended to the same keyframe');
  assert.equal(element('empty').hidden,true);assert.match(element('status').textContent,/H\.264 · Live host/);
  assert.match(element('metrics').textContent,/arrival max 1000 ms/);
  const measured=JSON.parse(element('timingReport').textContent);
  assert.equal(measured.arrival.gapsAtLeast1s,1);assert.equal(measured.canvasDraw.gapsAtLeast1s,1);
  assert.equal(measured.scope,'screen-mirror-observer');
  clock+=5000;intervals[0]();assert.match(element('status').textContent,/No new decoded frame/);
  await frame(false,5);assert.match(element('status').textContent,/H\.264 · Live host/);
  const sameSocket=liveSocket;document.hidden=true;listeners.get('visibilitychange')();
  await frame(false,6);document.hidden=false;listeners.get('visibilitychange')();
  assert.match(element('empty').textContent,/Capture connected · waiting/);
  await frame(false,7);assert.match(element('metrics').textContent,/keyframe-required/);
  assert.match(element('metrics').textContent,/received video packets/);
  clock+=2000;intervals[1]();assert.match(element('metrics').textContent,/packet age 2\.0 s/);
  await frame(true,5);assert.match(element('metrics').textContent,/nonadvancing-packet-timestamp/);
  await frame(true,8);assert.equal(liveSocket,sameSocket);assert.equal(element('empty').hidden,true);
  assert.match(element('status').textContent,/H\.264 · Live host/);
  await liveSocket.onmessage({data:body(true,false,0,[0,0,0,1,0x67,0x64,0,0x1f])});
  await frame(false,0);assert.equal(element('empty').hidden,false);
  await frame(true,1);assert.equal(element('empty').hidden,true,'explicit new config admits its new keyframe epoch');
  assert.equal(liveSocket,sameSocket);
  const beforeHardBound=liveDecoder;liveDecoder.decodeQueueSize=128;await frame(false,2);
  assert.notEqual(liveDecoder,beforeHardBound);assert.equal(element('empty').hidden,false);
  await frame(false,3);assert.equal(liveDecoder.submitted.length,0,'hard-bound recovery cannot submit a dependent delta');
  await frame(true,4);assert.equal(element('empty').hidden,true);assert.equal(liveSocket,sameSocket);
  sourceWidth=100;sourceHeight=50;let presentationPts=4;const presentationDecoder=liveDecoder;
  for(const [view,width,height,rect] of [['full',100,50,[0,0,100,50]],['left',39,45,[8,4,39,45]],['right',39,45,[52,4,39,45]],['crop',20,10,[2,3,20,10]],['composite',39,45,null]]){
    element('view').value=view;element('crop').value='20:10:2:3';
    const first=canvasResets.length;await frame(false,++presentationPts);
    assert.equal(element('screen').width,width);assert.equal(element('screen').height,height);
    if(rect)assert.deepEqual(draws.at(-1).slice(1,5),rect);
    const afterFirst=canvasResets.length;await frame(false,++presentationPts);
    assert.equal(canvasResets.length,afterFirst,'same dimensions never reset either canvas');
    assert.ok(canvasResets.slice(first).filter(r=>r.id==='screen').length<=2,'a mode change resizes directly to final output dimensions');
    assert.equal(liveDecoder,presentationDecoder,'presentation changes preserve the decoder');
  }
  liveDecoder.options.error(new Error('fixture failure'));const error=element('status').textContent;
  liveDecoder.options.output({displayWidth:1344,displayHeight:704,close(){}});assert.equal(element('status').textContent,error);
  element('stop').onclick();liveDecoder.options.output({displayWidth:1344,displayHeight:704,close(){}});assert.equal(element('status').textContent,'Disconnected');
  assert.match(element('empty').textContent,/Choose a configured stream/);
  await element('stopHost').onclick();assert.match(element('status').textContent,/requested · actual capture cleanup pending/);
  assert.equal(requests.filter(r=>r.options?.method==='POST').length,2);
  assert.match(requests.find(r=>r.url.includes('/api/captures/')).url,/\/start/);
});
